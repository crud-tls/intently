// Generates apps/hub/public/_redirects from docs/legacy-urls.txt: every path the old
// liveintently.app served either stays on the hub or gets one 301 to its new home.
// Run after editing the legacy list or the rules below:  node tools/hub-redirects.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const RESPITE = 'https://respite.liveintently.app';

// Respite serves its pages at /page/ and answers /page with a temporary 307, so point straight at
// the slashed URL: one permanent hop is what lets Google move the old rankings across.
const slashed = (url) => url.replace(/^(https:\/\/[^/]+(?:\/[^#?]*)?)([#?].*)?$/, (all, path, rest = '') =>
	/\/$|\.[a-z0-9]+$/i.test(path.split('/').pop() || '/') || path.endsWith('/') ? all : `${path}/${rest}`);

// Paths the hub serves itself.
const KEEP = new Set(['/', '/about', '/contact', '/api/contact', '/404', '/robots.txt',
	'/sitemap-index.xml', '/sitemap-0.xml', '/favicon.svg', '/favicon.ico', '/logo.png', '/logo.svg']);

// The Android app's App Links file is deliberately not served on the apex any more: it would make
// every studio link open the Respite app. Shipped versions keep their verification until they update.
const DROP = new Set(['/.well-known/assetlinks.json']);

// Paths that changed on the way to their new site; everything else keeps its path on Respite.
// The old site was the Android and Chrome app, so its policy and terms are Respite's Android ones.
const RENAMED = {
	'/privacy': `${RESPITE}/privacy/android`,
	'/terms': `${RESPITE}/terms/android`,
	'/privacy-chrome': `${RESPITE}/privacy/chrome`,
	'/privacy-policy-chrome': `${RESPITE}/privacy/chrome`,
	'/privacy-policy-chrome.html': `${RESPITE}/privacy/chrome`,
	'/privacy-loop': 'https://loop.liveintently.app/privacy',
	'/confirm-deletion': `${RESPITE}/delete-account/confirm`,
	'/resources': `${RESPITE}/blog`,
	'/comparisons': `${RESPITE}/blog#comparisons`,
	'/guides/screen-time-reduction': `${RESPITE}/blog#getting-started`,
};

const paths = readFileSync(new URL('../docs/legacy-urls.txt', import.meta.url), 'utf8')
	.split('\n').filter((l) => l && !l.startsWith('#')).map((l) => l.split(' ')[1]);

const lines = [
	'# Generated by tools/hub-redirects.mjs from docs/legacy-urls.txt. Do not edit by hand.',
	'# The old single-site liveintently.app was the site of the Android and Chrome apps; its pages now live on',
	'# respite.liveintently.app and the apex is the Intently studio hub.',
	'',
];
// Pages were also reachable with a trailing slash; files were not.
const rule = (from, to) => {
	to = slashed(to);
	lines.push(`${from}  ${to}  301`);
	if (!from.includes('.') && from !== '/') lines.push(`${from}/  ${to}  301`);
};
for (const [from, to] of Object.entries(RENAMED)) rule(from, to);
for (const p of paths) {
	if (KEEP.has(p) || DROP.has(p) || RENAMED[p] || p.startsWith('/blog')) continue;
	rule(p, `${RESPITE}${p}`);
}
// Blog paths keep their path; the Respite site itself 301s the renamed intently-vs-* posts.
// (Cloudflare splats only follow a "/", so a prefix rule like /blog/intently-vs-* never matches.)
rule('/blog', `${RESPITE}/blog`);
lines.push(`/blog/*  ${RESPITE}/blog/:splat  301`);
lines.push(`/blog-*  ${RESPITE}/blog-:splat  301`);
lines.push(`/rss.xml  ${RESPITE}/rss.xml  301`);

// A redirect must never shadow a page the hub serves (Cloudflare applies _redirects first).
const pagesDir = new URL('../apps/hub/src/pages/', import.meta.url);
const hubPages = readdirSync(pagesDir, { recursive: true })
	.filter((f) => f.endsWith('.astro') && !f.startsWith('api'))
	.map((f) => '/' + f.replace(/\.astro$/, '').replace(/(^|\/)index$/, ''))
	.map((p) => (p.length > 1 ? p.replace(/\/$/, '') : p));
for (const line of lines.filter((l) => l.startsWith('/'))) {
	const from = line.split(/\s+/)[0].replace(/\/$/, '').replace(/\*$/, '') || '/';
	const clash = hubPages.find((p) => p !== '/' && (from === p || from.startsWith(p + '/')));
	if (clash) throw new Error(`_redirects rule "${line}" would shadow the hub page ${clash}`);
}

writeFileSync(new URL('../apps/hub/public/_redirects', import.meta.url), [...new Set(lines)].join('\n') + '\n');
console.log(`wrote ${lines.length - 4} rules`);
